export type FlatNote = NoteRef & { domain: Domain; groupIndex: number; groupName: string; index: number };

export const ALL_NOTES: FlatNote[] = DOMAINS.flatMap((d) =>
  d.groups.flatMap((g, gi) => g.notes.map((n, ni) => ({ ...n, domain: d, groupIndex: gi, groupName: g.name, index: ni }))),
);

const NOTE_BY_ID = new Map(ALL_NOTES.map((n) => [n.id, n]));
const DOMAIN_BY_SLUG = new Map(DOMAINS.map((d) => [d.slug, d]));

export function findDomain(slug: string): Domain | undefined {
  return DOMAIN_BY_SLUG.get(slug);
}

export function findNote(id: string): FlatNote | undefined {
  return NOTE_BY_ID.get(id);
}

export function noteCount(d: Domain): number {
  return d.groups.reduce((s, g) => s + g.notes.length, 0);
}

/** 「領域 / グループ」の表示用の場所 */
export function notePath(n: FlatNote): string {
  return `${n.domain.name} / ${n.groupName}`;
}
