// PM Playbook の階層（領域 → グループ → ノート）
//
// ノートIDは並び順から「n{領域}-{グループ}-{順番}」で決まり、本文は content/notes/{id}.mdx に置く。
// IDは位置で決まるので、ノートやグループを途中に差し込むと後ろのIDがずれる（ファイル名とリンクが合わなくなる）。
// 追加はグループの末尾に行い、並べ替えるときはファイル名と <NoteLink> もあわせて直す。
// `npm run check:content` が、構成とファイルの食い違いやリンク切れを検出する。

export type NoteRef = { id: string; title: string; desc?: string };
export type Group = { name: string; notes: NoteRef[] };
export type Domain = {
  no: number;
  slug: string;
  name: string;
  desc: string;
  /** グループを「1から順に進める」並びとして見せるか（STEP番号を付ける） */
  ordered: boolean;
  groups: Group[];
};

/** ノートはタイトルだけ、または［タイトル, 一覧で添える短い説明］で書く */
type NoteSpec = string | [title: string, desc: string];
type GroupSpec = [name: string, notes: NoteSpec[]];
type DomainSpec = Omit<Domain, "groups"> & { groups: GroupSpec[] };

function defineDomain(spec: DomainSpec): Domain {
  return {
    ...spec,
    groups: spec.groups.map(([name, notes], gi) => ({
      name,
      notes: notes.map((n, ni) => {
        const [title, desc] = typeof n === "string" ? [n, undefined] : n;
        return { id: `n${spec.no}-${gi + 1}-${ni + 1}`, title, desc };
      }),
    })),
  };
}

